"""
GFlowNet training for quantum measurement circuit optimization.

This module implements GFlowNet-based learning to generate measurement circuits
for quantum energy estimation using shadow tomography.

Key Components:
===============
- GFlowNetTrainer: Main training loop for circuit generation
- Measurement backend: Tracks Clifford tableau data for Pauli transformations
- EnergyEstimator: Evaluates circuit quality via energy estimation

GFlowNet Protocol:
    1. State: Current partial circuit (sequence of Clifford gates)
    2. Action: Append a gate (H, S, HS, SH, HSH, CNOT) or terminate
    3. Reward: Based on energy estimation accuracy (lower cost = higher reward)
    4. Flow: Learn P(circuit) ∝ exp(reward) via trajectory balance

Tensor Shapes:
    batch_actions: (B, C, L) - B parallel trajectories, C circuits each, L max gates
    batch_lengths: (B, C) - actual circuit lengths
    clifford_maps: (B, C, 2n, 2n) - Clifford tableaux for n qubits
"""

